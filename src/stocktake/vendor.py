"""Building the single-file copy of StockTake's core, for a project that cannot take a dependency ([ADR 0005](adr/0005-installed-package-plus-a-generated-single-file-copy.md)).

The file is generated and never written by hand: the package stays the only source of truth. The core modules are emitted in dependency
order, with their imports of each other removed and every other import hoisted to the top, so the result is one flat module that reads as the
concatenation of files that were each already linted and type-checked.

Three things make that safe rather than merely clever:

- **The generator refuses to emit anything if two modules define the same top-level name.** In one flat file the second would silently shadow
  the first, which is the kind of bug that produces wrong answers rather than crashes. There are no such collisions today, and if a change
  introduces one this stops with the name and both files.
- **The order is computed, not listed.** A new module is picked up and placed by its imports, so the generator cannot fall behind the package.
- **`tests/test_vendor.py` regenerates the committed copy and insists it is identical**, and runs the generated module against the package on
  the same project to insist the two agree.

What the copy does not include: the pytest plugin (it needs pytest), `stocktake init`, the command line, and this generator. It is a library —
`run_check`, `skip_reason`, `update_warning`, `failure_text`, and everything those stand on.
"""

from __future__ import annotations

import ast
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

PACKAGE_ROOT = Path(__file__).resolve().parent
VENDORED_NAME = "stocktake_vendored.py"

# Not part of the core: the public re-exports (everything is top-level in one file anyway), the entry points, the pytest integration, the
# file-writing command, and this generator.
EXCLUDED_FILES = frozenset({"__main__.py", "cli.py", "pytest_plugin.py", "init_project.py", "vendor.py"})
EXCLUDED_DIRECTORIES = frozenset({"templates"})

# Package `__init__` files that define something rather than only re-exporting. `registries/__init__.py` holds the Registries facade.
KEPT_PACKAGE_INITS = frozenset({"registries"})

HEADER = '''"""StockTake's dependency check, as one self-contained file.

Generated by `stocktake vendor` from StockTake {version}. Do not edit: regenerate it instead, or the next regeneration will overwrite you.
The package it came from is at {home}.

This is the core as a library. It reads what a project pins, asks the public registries whether a newer release exists and whether the pinned
one has a known advisory, and judges the answers. It never edits a file, and the only thing it sends is package names and versions.

    import stocktake_vendored as stocktake

    report = stocktake.run_check(Path("."))
    assert stocktake.failure_text(report) is None     # fails on vulnerable, withdrawn, or an overdue policy entry

    if stocktake.skip_reason(report):                 # the registries could not be reached: not a failure
        ...
    if stocktake.update_warning(report):              # a newer release exists: a warning, never a failure
        ...

Not included, because they need things a single file cannot carry: the pytest plugin, `stocktake init`, and the command line.
"""
'''

HOME = "https://github.com/BlackCanyonSoftware/stocktake_BCS"
SEPARATOR = "# " + "=" * 118


class VendorError(RuntimeError):
    """The copy could not be generated. Always a problem in the package, never in the caller."""


@dataclass(frozen=True, slots=True)
class Module:
    """One core module, ready to be emitted."""

    name: str  # "stocktake.models"
    path: Path
    body: str  # its source with intra-package imports and __all__ removed
    imports: frozenset[str]  # the import lines to hoist
    defines: frozenset[str]  # its top-level names, for the collision check
    needs: frozenset[str]  # the stocktake modules or packages it imports from
    aliases: tuple[tuple[str, str], ...]  # (as written, original) for an intra-package import that renamed something


def module_name(path: Path, root: Path = PACKAGE_ROOT) -> str:
    parts = [part for part in path.relative_to(root).with_suffix("").parts if part != "__init__"]
    return ".".join(["stocktake", *parts])


def core_paths(root: Path = PACKAGE_ROOT) -> list[Path]:
    """Every file that belongs in the copy, in a stable order."""
    found = []
    for path in sorted(root.rglob("*.py")):
        relative = path.relative_to(root)
        if path.name in EXCLUDED_FILES or EXCLUDED_DIRECTORIES & set(relative.parts):
            continue
        if path.name == "__init__.py" and not (relative.parent.parts and relative.parent.parts[-1] in KEPT_PACKAGE_INITS):
            continue
        found.append(path)
    return found


def _read(path: Path, root: Path) -> Module:
    source = path.read_text(encoding="utf-8")
    lines = source.splitlines()
    tree = ast.parse(source)

    dropped: set[int] = set()  # 1-based line numbers to leave out
    imports: set[str] = set()
    defines: set[str] = set()
    needs: set[str] = set()
    aliases: list[tuple[str, str]] = []

    for node in tree.body:
        if isinstance(node, ast.ImportFrom):
            target = node.module or ""
            dropped.update(range(node.lineno, (node.end_lineno or node.lineno) + 1))
            if target == "__future__":
                continue
            if target.startswith("stocktake"):
                needs.add(target)
                # `from stocktake.readers import groups as reader_groups` loses its new name when the import line goes. Without putting the
                # name back, the flat file would raise NameError the first time that code ran — and only then, not at import.
                aliases += [(alias.asname, alias.name) for alias in node.names if alias.asname]
                continue
            for alias in node.names:
                imports.add(f"from {target} import {alias.name}" + (f" as {alias.asname}" if alias.asname else ""))
        elif isinstance(node, ast.Import):
            dropped.update(range(node.lineno, (node.end_lineno or node.lineno) + 1))
            for alias in node.names:
                if alias.name.startswith("stocktake"):
                    needs.add(alias.name)
                    continue
                imports.add(f"import {alias.name}" + (f" as {alias.asname}" if alias.asname else ""))
        elif isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "__all__" for t in node.targets):
            dropped.update(range(node.lineno, (node.end_lineno or node.lineno) + 1))  # meaningless in one flat module, and it would collide
        else:
            defines.update(_defined_by(node))

    body = "\n".join(line for number, line in enumerate(lines, 1) if number not in dropped)
    return Module(
        name=module_name(path, root),
        path=path,
        body=body.strip("\n"),
        imports=frozenset(imports),
        defines=frozenset(defines),
        needs=frozenset(needs),
        aliases=tuple(sorted(set(aliases))),
    )


def _defined_by(node: ast.stmt) -> set[str]:
    if isinstance(node, ast.ClassDef | ast.FunctionDef | ast.AsyncFunctionDef):
        return {node.name}
    if isinstance(node, ast.Assign):
        return {target.id for target in node.targets if isinstance(target, ast.Name)}
    if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
        return {node.target.id}
    return set()


def collisions(modules: list[Module]) -> dict[str, list[str]]:
    """Top-level names defined by more than one module. Must be empty: in one flat file, the second definition wins silently."""
    where: dict[str, list[str]] = defaultdict(list)
    for module in modules:
        for name in module.defines:
            where[name].append(module.name)
        for renamed, _original in module.aliases:
            where[renamed].append(f"{module.name} (as a renamed import)")
    return {name: sorted(names) for name, names in where.items() if len(names) > 1}


def missing_dependencies(modules: list[Module]) -> dict[str, list[str]]:
    """What the copy imports but does not contain.

    The failure this catches: `cli.py` imports from `init_project.py`, which is deliberately left out, so a flat file containing the first
    and not the second would raise NameError the first time that code ran. A module that needs something excluded has to be excluded too.
    """
    by_name = {module.name: module for module in modules}
    gaps: dict[str, list[str]] = {}
    for module in modules:
        absent = sorted(
            need
            for need in module.needs
            if need not in by_name and not any(name.startswith(need + ".") for name in by_name) and need != "stocktake"
        )
        if absent:
            gaps[module.name] = absent
    return gaps


def dependency_order(modules: list[Module]) -> list[Module]:
    """The modules sorted so that each comes after everything it imports from.

    Computed rather than listed, so a new module places itself. Ties break on the module name, so the output is byte-for-byte stable.
    """
    by_name = {module.name: module for module in modules}

    def resolve(target: str) -> set[str]:
        """The emitted modules an import of `target` depends on: itself if it is one, else everything in that package."""
        if target in by_name:
            return {target}
        return {name for name in by_name if name.startswith(target + ".")}

    waiting_on = {module.name: {dep for need in module.needs for dep in resolve(need)} - {module.name} for module in modules}

    ordered: list[Module] = []
    remaining = dict(waiting_on)
    while remaining:
        ready = sorted(name for name, needs in remaining.items() if not needs - {m.name for m in ordered})
        if not ready:
            raise VendorError(f"these modules import each other in a cycle: {sorted(remaining)}")
        for name in ready:
            ordered.append(by_name[name])
            del remaining[name]
    return ordered


def render(root: Path = PACKAGE_ROOT, version: str | None = None) -> str:
    """The whole copy, as text. Raises VendorError rather than emitting something that would be subtly wrong."""
    modules = [_read(path, root) for path in core_paths(root)]
    if not modules:
        raise VendorError(f"no core modules found under {root}")

    clashing = collisions(modules)
    if clashing:
        detail = "; ".join(f"{name} in {' and '.join(where)}" for name, where in sorted(clashing.items()))
        raise VendorError(f"two core modules define the same top-level name, which one flat file cannot carry: {detail}")

    gaps = missing_dependencies(modules)
    if gaps:
        detail = "; ".join(f"{name} needs {', '.join(absent)}" for name, absent in sorted(gaps.items()))
        raise VendorError(f"the copy would import something it does not contain: {detail}")

    if version is None:
        from stocktake._version import __version__

        version = __version__

    pieces = [
        HEADER.format(version=version, home=HOME),
        "from __future__ import annotations",
        "",
        "\n".join(sorted({line for module in modules for line in module.imports})),
    ]
    for module in dependency_order(modules):
        pieces += ["", SEPARATOR, f"# {module.name}", SEPARATOR, "", module.body]

    renamed = sorted({alias for module in modules for alias in module.aliases})
    if renamed:
        pieces += [
            "",
            SEPARATOR,
            "# names that were renamed on import, put back",
            SEPARATOR,
            "",
            *[f"{new} = {original}" for new, original in renamed],
        ]
    return "\n".join(pieces).rstrip("\n") + "\n"


def write(target: Path, root: Path = PACKAGE_ROOT, version: str | None = None) -> Path:
    """Write the copy. `target` may be the file to write or a directory to write `stocktake_vendored.py` into.

    A path that does not exist yet is taken for a directory unless it is named like a Python file. `stocktake vendor deps` used to write a
    Python module into a file called `deps`, which nothing can import and which looks like the command having gone wrong — and the directory
    the person meant is created either way, so there is no case where guessing "file" is the more helpful reading.
    """
    directory = target.is_dir() or (not target.exists() and target.suffix not in (".py", ".pyi"))
    path = target / VENDORED_NAME if directory else target
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(root, version), encoding="utf-8")
    return path
