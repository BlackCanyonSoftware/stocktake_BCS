"""The report a program reads.

Every field, stable keys, one object. `fix_target` is computed here because a caller that has to work out the upgrade target itself would
have to reimplement the rule about backported fixes, and get it wrong.
"""





def _finding(finding: Finding) -> dict[str, Any]:
    return {
        **asdict(finding.dep),
        "status": finding.status,
        "severity": finding.severity,
        "latest": finding.latest,
        "update": finding.update,
        "note": finding.note,
        "advisories": [asdict(a) for a in finding.advisories],
        "fix_target": fix_target(finding.advisories, finding.dep.version or "0", finding.dep.ecosystem) if finding.advisories else None,
    }


def as_dict(report: Report) -> dict[str, Any]:
    """The report as plain data, for a caller that wants it in process rather than as text."""
    return {
        "date": report.today,
        "offline": report.offline,
        "failed": report.failed,
        "counts": report.counts,
        "notes": list(report.notes),
        "config_source": report.config_source,
        "policy_problems": list(report.policy_problems),
        "unread_manifests": list(report.unread_manifests),
        # Manifests the project has accepted as unreadable. Not in the text report, because it asked not to be nagged — but never invisible.
        "accepted_unread": list(report.accepted_unread),
        "findings": [_finding(f) for f in report.findings],
    }


def render_json(report: Report) -> str:
    return json.dumps(as_dict(report), indent=2)

# ======================================================================================================================
# stocktake.report.sarif
# ======================================================================================================================

"""SARIF 2.1.0, so an editor and GitHub's code-scanning view can put the findings on the lines they came from.

Which findings become results is a judgement, not a translation. `vulnerable` and `yanked` are errors, and so is a policy entry that has run
out. A newer release, an unpinned install and an answer we could not get are notes. `current` is not a finding at all, and `held` is a
decision the project has already recorded and does not need shown back to it. `--only` narrows this the same way it narrows the text report.

Anything about the *run* rather than about a dependency — an environment that could not be found, registries that could not be reached — goes
in the invocation's notifications, which is where SARIF puts that kind of thing, rather than being dressed up as a finding.
"""




SCHEMA = "https://json.schemastore.org/sarif-2.1.0.json"
SARIF_VERSION = "2.1.0"
INFORMATION_URI = "https://github.com/BlackCanyonSoftware/stocktake_BCS"

# The SARIF level for each status worth reporting. A status absent from here produces no result.
LEVELS: dict[str, str] = {
    "vulnerable": "error",
    "yanked": "error",
    "outdated": "note",
    "unpinned": "note",
    "unknown": "note",
}

POLICY_RULE = "policy"
UNREAD_RULE = "unread"

RULES: dict[str, tuple[str, str]] = {
    "vulnerable": ("Vulnerable dependency", "A dependency is at a version with a known published security advisory against it."),
    "yanked": ("Withdrawn release", "A dependency is at a release its own author has since withdrawn."),
    "outdated": ("Newer release available", "A newer release of this dependency exists. Being behind is not a failure."),
    "unpinned": ("No version fixed", "Nothing fixes this dependency's version, so what gets installed depends on when."),
    "unknown": ("Could not be checked", "This dependency could not be looked up, so nothing is claimed about it either way."),
    POLICY_RULE: ("Policy entry overdue", "A decision recorded in the project's config has passed the date it was to be made again."),
    UNREAD_RULE: (
        "Manifest not read",
        "This file declares dependencies of a kind StockTake has no reader for, so nothing in it was checked.",
    ),
}


def _location(source: str) -> dict[str, Any]:
    """A SARIF location from a `path` or `path:line` source. `%SRCROOT%` is the convention GitHub resolves against the repository root."""
    path, _, line = source.rpartition(":")
    if path and line.isdigit():
        region = {"region": {"startLine": int(line)}}
    else:
        path, region = source, {}
    return {"physicalLocation": {"artifactLocation": {"uri": path, "uriBaseId": "%SRCROOT%"}, **region}}


def _message(finding: Finding) -> str:
    dep = finding.dep
    where = f"{dep.name} {dep.version}" if dep.version else dep.name

    if finding.status == "vulnerable":
        plural = "advisory" if len(finding.advisories) == 1 else "advisories"
        target = fix_target(finding.advisories, dep.version or "0", dep.ecosystem)
        advice = f"Upgrade to {target} or newer." if target else "No fixed version is named."
        listed = ", ".join(advisory.id for advisory in finding.advisories[:5])
        more = f" and {len(finding.advisories) - 5} more" if len(finding.advisories) > 5 else ""
        return f"{where} has {len(finding.advisories)} known {plural} ({listed}{more}). {advice}"

    if finding.status == "yanked":
        return f"{where} is a release its author has withdrawn. The newest release is {finding.latest}."

    if finding.status == "outdated":
        return f"{where} has a newer release: {finding.latest} ({finding.update})."

    return f"{where}: {finding.note}" if finding.note else where


def _result(finding: Finding) -> dict[str, Any]:
    dep = finding.dep
    return {
        "ruleId": finding.status,
        "level": LEVELS[finding.status],
        "message": {"text": _message(finding)},
        "locations": [_location(dep.source)],
        # Enough to recognise the same problem across runs, and to tell two declarations of one package apart.
        "partialFingerprints": {"stocktakeFinding": f"{dep.ecosystem}/{dep.name}/{finding.status}/{dep.source}"},
    }


def _rules_used(ids: list[str]) -> list[dict[str, Any]]:
    """One rule per id actually used, in a stable order. SARIF wants every ruleId a result refers to declared here."""
    order = [*STATUSES, POLICY_RULE, UNREAD_RULE]
    return [
        {
            "id": rule_id,
            "name": RULES[rule_id][0],
            "shortDescription": {"text": RULES[rule_id][0]},
            "fullDescription": {"text": RULES[rule_id][1]},
            "help": {"text": RULES[rule_id][1]},
            "defaultConfiguration": {"level": LEVELS.get(rule_id, "error" if rule_id == POLICY_RULE else "note")},
        }
        for rule_id in order
        if rule_id in set(ids) and rule_id in RULES
    ]


def as_sarif(report: Report, only: str = "all") -> dict[str, Any]:
    """The report as a SARIF log, as plain data."""
    shown = shown_statuses(only)
    results = [_result(f) for f in report.findings if f.status in LEVELS and f.status in shown]

    if report.policy_problems and "vulnerable" in shown:  # an overdue policy entry fails the build, so it belongs wherever failures do
        location = [_location(report.config_source)] if report.config_source else []
        results += [
            {
                "ruleId": POLICY_RULE,
                "level": "error",
                "message": {"text": problem},
                **({"locations": location} if location else {}),
                "partialFingerprints": {"stocktakeFinding": f"policy/{problem}"},
            }
            for problem in report.policy_problems
        ]

    if "unpinned" in shown:
        results += [
            {
                "ruleId": UNREAD_RULE,
                "level": "note",
                "message": {"text": f"{name} declares dependencies of a kind StockTake has no reader for, so nothing in it was checked."},
                "locations": [_location(name)],
                "partialFingerprints": {"stocktakeFinding": f"unread/{name}"},
            }
            for name in report.unread_manifests
        ]

    notifications = [{"level": "warning", "message": {"text": note}} for note in report.notes]
    if report.offline:
        notifications.append({"level": "error", "message": {"text": f"The check could not be completed: {report.offline}"}})

    return {
        "version": SARIF_VERSION,
        "$schema": SCHEMA,
        "runs": [
            {
                "tool": {
                    "driver": {
                        "name": "StockTake",
                        "version": __version__,
                        "informationUri": INFORMATION_URI,
                        "rules": _rules_used([str(r["ruleId"]) for r in results]),
                    }
                },
                "invocations": [
                    {
                        "executionSuccessful": report.offline is None,
                        **({"toolExecutionNotifications": notifications} if notifications else {}),
                    }
                ],
                "results": results,
            }
        ],
    }


def render_sarif(report: Report, only: str = "all") -> str:
    return json.dumps(as_sarif(report, only), indent=2)

# ======================================================================================================================
# stocktake.report.text
# ======================================================================================================================

"""The report a person reads.

The layout is the design, not decoration (docs/DESIGN.md): what must be fixed comes first, `current` collapses to a count so a long clean
list cannot bury a short dirty one, the source location leads every row so the output stays greppable, and every "there is more than this"
names the exact command that shows the rest.

No colour, no box drawing, no spinners. This text lands in pytest summaries, CI logs and pipes, where all of that becomes noise — and
severity carried by the word rather than the colour is the accessible choice anyway.
"""




_HINT = "stocktake --only vulnerable --all-advisories"


def _source_width(findings: Sequence[Finding]) -> int:
    """Wide enough for the paths actually present, within reason, so rows line up without the file names being cut off."""
    longest = max((len(f.dep.source) for f in findings), default=0)
    return max(24, min(longest + 2, 44))


def _rows(report: Report, status: str) -> list[Finding]:
    """The findings of one status, ordered by where they came from, so the report reads the way the project is laid out."""
    return sorted((f for f in report.findings if f.status == status), key=lambda f: (f.dep.source, f.dep.name))


def _headline(report: Report) -> str:
    counts = report.counts
    line = (
        f"Dependency check {report.today}: {len(report.findings)} checked, "
        f"{counts['vulnerable']} vulnerable, {counts['yanked']} withdrawn, {counts['outdated']} outdated, {counts['unpinned']} unpinned"
    )
    return f"{line}  [{report.offline}]" if report.offline else line


def _vulnerable_row(finding: Finding, width: int, all_advisories: bool, top: int) -> list[str]:
    dep = finding.dep
    tally = ", ".join(f"{count} {label}" for label, count in severity_tally(finding.advisories))
    plural = "advisory" if len(finding.advisories) == 1 else "advisories"
    target = fix_target(finding.advisories, dep.version or "0", dep.ecosystem)
    fix = f"; upgrade to {target} or newer" if target else "; no fixed version named"
    # Two spaces after the version: "pillow 9.0.0 52 advisories" otherwise reads as though the version were "9.0.0 52".
    lines = [f"  {dep.source:<{width}} {dep.name} {dep.version}  {len(finding.advisories)} {plural} ({tally}){fix}"]

    shown = finding.advisories if all_advisories else finding.advisories[:top]
    lines += [f"      {a.id} {a.label}: {a.summary}" for a in shown]
    if len(shown) < len(finding.advisories):
        lines.append(f"      ... and {len(finding.advisories) - len(shown)} more ({_HINT})")
    return lines


def render_text(report: Report, only: str = "all", all_advisories: bool = False, top: int = 5) -> str:
    """The whole report as text. `only` narrows it to what needs action; `top` is how many advisories a package shows before they are counted."""
    shown = shown_statuses(only)
    width = _source_width(report.findings)
    lines = [_headline(report)]

    if not report.findings:
        # Silence looks like success, and it almost never is. A project with no dependencies at all is far rarer than a misconfigured scan.
        lines += [
            "",
            "Nothing was found to check. If that is a surprise, the project's excludes or enabled ecosystems are the place to look.",
        ]

    # Anything that affects how much of the report can be trusted comes before the findings themselves.
    for note in report.notes:
        lines += ["", f"NOTE: {note}"]

    for problem in report.policy_problems:
        lines += ["", f"POLICY: {problem}"]

    if report.unread_manifests:
        lines += ["", "UNREAD (StockTake has no reader for these yet, so nothing in them was checked)"]
        lines += [f"  {name}" for name in report.unread_manifests]

    for status in STATUSES:
        rows = _rows(report, status)
        if not rows or status not in shown:
            continue
        if status == "current":
            lines += ["", f"CURRENT: {len(rows)} up to date"]
            continue
        lines += ["", status.upper() + (" (fix these)" if status in ("vulnerable", "yanked") else "")]
        for finding in rows:
            if status == "vulnerable":
                lines += _vulnerable_row(finding, width, all_advisories, top)
                continue
            dep = finding.dep
            row = f"  {dep.source:<{width}} {dep.name} {dep.version or '(none)'}"
            if finding.latest and status in ("outdated", "held"):
                row += f" -> {finding.latest} ({finding.update})"
            lines.append(row + (f"  {finding.note}" if finding.note else ""))

    return "\n".join(lines)

# ======================================================================================================================
# stocktake.config
# ======================================================================================================================

"""Where a project says what to read, what to skip and what has been decided: `.stocktake.toml` at its root, or a `[tool.stocktake]` table in
`pyproject.toml` for a Python project that would rather not have another file (docs/adr/0002).

The point of this module is that nothing in StockTake's source knows about any particular project. The original's hard-coded exclusion list,
naming folders that exist in exactly one repository, is what made it impossible to reuse; everything of that kind lives here instead.

Every value is validated when it is read, and a file that cannot be understood is refused rather than quietly replaced by defaults — a policy
that silently stopped applying would be the one failure a policy file must not have.
"""




CONFIG_NAME = ".stocktake.toml"

# Folders no project means to have scanned. Generic on purpose: anything project-specific belongs in that project's own config file.
DEFAULT_EXCLUDES: tuple[str, ...] = (
    ".git",
    ".hg",
    ".svn",
    ".venv",
    "venv",
    "env",
    "node_modules",
    "__pycache__",
    "site-packages",
    "dist",
    "build",
    "*.egg-info",
    ".tox",
    ".nox",
    ".eggs",
    ".mypy_cache",
    ".pytest_cache",
    ".ruff_cache",
    ".idea",
    ".vscode",
)

DEFAULT_CACHE_TTL_HOURS = 6.0


class ConfigError(ValueError):
    """The config file could not be read. Said plainly and at once, rather than guessing at a default."""


@dataclass(frozen=True, slots=True)
class Config:
    """What one project has configured."""

    policy: Policy = field(default_factory=Policy)
    exclude: tuple[str, ...] = ()  # added to DEFAULT_EXCLUDES, never replacing them
    ecosystems: tuple[str, ...] | None = None  # which reader groups to run; None means all of them
    accept_unread: tuple[str, ...] = ()  # manifests the project knows StockTake cannot read, and accepts
    environment: str | None = None  # the Python environment whose installed versions to use, relative to the project root
    cache_ttl_hours: float = DEFAULT_CACHE_TTL_HOURS
    source: str | None = None  # the file this came from, so it can be said which one was used

    @property
    def excludes(self) -> tuple[str, ...]:
        return DEFAULT_EXCLUDES + self.exclude

    @property
    def cache_ttl_seconds(self) -> int:
        return int(self.cache_ttl_hours * 3600)


def excluded(relative_path: str, patterns: Sequence[str]) -> bool:
    """Whether a path relative to the project root matches one of a set of patterns.

    A pattern matches either the whole relative path (`tests/fixtures`) or any single segment of it (`.venv`, `*.egg-info`), so the obvious
    thing to write in a config file is the thing that works. Used for both `exclude` and `accept_unread`.
    """
    segments = relative_path.split("/")
    return any(fnmatch(relative_path, p) or any(fnmatch(segment, p) for segment in segments) for p in patterns)


def _read_toml(path: Path) -> dict[str, Any]:
    try:
        with path.open("rb") as handle:
            return tomllib.load(handle)
    except OSError as exc:
        raise ConfigError(f"{path}: could not be read ({exc})") from exc
    except tomllib.TOMLDecodeError as exc:
        raise ConfigError(f"{path}: is not valid TOML ({exc})") from exc


def _string_list(path: Path, table: Mapping[str, Any], key: str) -> tuple[str, ...]:
    value = table.get(key) or []
    if not isinstance(value, list) or any(not isinstance(item, str) for item in value):
        raise ConfigError(f"{path}: `{key}` must be a list of strings")
    return tuple(value)


def _ecosystems(path: Path, table: Mapping[str, Any]) -> tuple[str, ...] | None:
    if "ecosystems" not in table:
        return None  # not mentioned means all of them, which is what a project with no config gets
    chosen = _string_list(path, table, "ecosystems")
    known = reader_groups()
    unknown = [name for name in chosen if name not in known]
    if unknown:
        raise ConfigError(f"{path}: unknown ecosystem(s) {', '.join(sorted(unknown))}; this version knows {', '.join(known)}")
    return chosen


def _cache_ttl_hours(path: Path, table: Mapping[str, Any]) -> float:
    cache = table.get("cache") or {}
    if not isinstance(cache, Mapping):
        raise ConfigError(f"{path}: `[cache]` must be a table")
    hours = cache.get("ttl_hours", DEFAULT_CACHE_TTL_HOURS)
    if isinstance(hours, bool) or not isinstance(hours, int | float) or hours <= 0:
        raise ConfigError(f"{path}: `cache.ttl_hours` must be a positive number")
    return float(hours)


def _environment(path: Path, table: Mapping[str, Any]) -> str | None:
    value = table.get("environment")
    if value is None:
        return None
    if not isinstance(value, str) or not value:
        raise ConfigError(f"{path}: `environment` must be a path, as a string")
    return value


def _build(path: Path, table: Mapping[str, Any]) -> Config:
    policy = table.get("policy") or {}
    if not isinstance(policy, Mapping):
        raise ConfigError(f"{path}: `[policy]` must be a table")
    return Config(
        policy=policy_from_toml(policy),
        exclude=_string_list(path, table, "exclude"),
        ecosystems=_ecosystems(path, table),
        accept_unread=_string_list(path, table, "accept_unread"),
        environment=_environment(path, table),
        cache_ttl_hours=_cache_ttl_hours(path, table),
        source=str(path),
    )


def load_config(root: Path, path: Path | None = None) -> Config:
    """The config for a project: an explicitly named file, else `.stocktake.toml`, else `[tool.stocktake]` in `pyproject.toml`, else defaults.

    `.stocktake.toml` wins over `pyproject.toml` rather than merging with it, and `Config.source` records which file was used.
    """
    if path is not None:
        return _build(path, _read_toml(path))

    own = root / CONFIG_NAME
    if own.is_file():
        return _build(own, _read_toml(own))

    pyproject = root / "pyproject.toml"
    if pyproject.is_file():
        table = _read_toml(pyproject).get("tool", {}).get("stocktake")
        if isinstance(table, Mapping):
            return _build(pyproject, table)

    return Config()

# ======================================================================================================================
# stocktake.registries
# ======================================================================================================================

"""Every registry client, wired to one shared cache.

This is the wiring, and the only place that knows which concrete clients exist. `evaluate()` is handed one `Registries` and never builds one,
which is precisely why the whole test suite runs with no network at all (docs/ARCHITECTURE.md).
"""






class Registries:
    """Every registry client behind one object, sharing one cache."""

    def __init__(
        self,
        cache: Cache | None = None,
        clients: Sequence[Client] | None = None,
        advisory_client: AdvisoryClient | None = None,
    ) -> None:
        self.cache = cache if cache is not None else Cache()
        chosen = clients if clients is not None else (PyPI(self.cache), Npm(self.cache), GitHub(self.cache))
        self.clients: dict[str, Client] = {client.ecosystem: client for client in chosen}
        self.advisory_client = advisory_client if advisory_client is not None else OSV(self.cache)

    @property
    def ecosystems(self) -> tuple[str, ...]:
        return tuple(self.clients)

    def latest(self, ecosystem: str, name: str) -> Versions | None:
        """The newest version of a name, or None when the registry does not have it. Raises rather than guessing when it cannot be asked."""
        client = self.clients.get(ecosystem)
        return client.latest(name) if client is not None else None

    def advisories(self, wanted: Sequence[Coordinate]) -> Mapping[Coordinate, tuple[Advisory, ...]]:
        return self.advisory_client.advisories(wanted)

    def flush(self) -> None:
        self.cache.flush()

# ======================================================================================================================
# stocktake.evaluate
# ======================================================================================================================

"""The judgement: a list of dependencies plus what the registries say, turned into a report.

Pure, given a `Registries` to ask. It constructs nothing, opens nothing and writes nothing, which is what makes the whole decision table
testable without a network (docs/ARCHITECTURE.md).

The decision table itself is [ADR 0004](adr/0004-only-unsafe-findings-fail-the-build.md) and is the heart of the product: vulnerable and
withdrawn releases fail, a newer release warns, and anything we could not find out is `unknown` rather than clean.
"""




# Enough to make a run of a few hundred dependencies quick, few enough to stay a polite guest on a free public service.
MAX_LOOKUPS_AT_ONCE = 8

# What an unpinned dependency means depends on who declared it, and the note has to say which.
UNPINNED_NOTES = {
    "image": "no version is pinned: whatever is newest when the image is built",
    "ci": "no version is pinned: whatever is newest when the workflow runs",
}
UNPINNED_DEFAULT = "not installed in this environment, and no version is pinned"

# A lookup either answers, or explains itself. The explanation is kept as a string so one failure cannot poison the whole run.
Answer = Versions | str | None


def _lookup(registries: Registries, ecosystem: str, name: str) -> Answer:
    if ecosystem not in registries.ecosystems:
        return f"no registry client for {ecosystem}"
    try:
        return registries.latest(ecosystem, name)
    except RateLimited as exc:
        return f"rate limited: {exc}"
    except OfflineError as exc:
        return f"offline: {exc}"


def _ask_about_every_name(deps: Sequence[Dep], registries: Registries) -> dict[tuple[str, str], Answer]:
    """One lookup per distinct name, several at a time. Two Dockerfiles pinning the same package ask about it once."""
    distinct = sorted({(d.ecosystem, d.name) for d in deps})
    if not distinct:
        return {}
    with ThreadPoolExecutor(max_workers=min(MAX_LOOKUPS_AT_ONCE, len(distinct))) as pool:
        answers = pool.map(lambda key: _lookup(registries, key[0], key[1]), distinct)
        return dict(zip(distinct, answers, strict=True))


def _unreachable(answers: Mapping[tuple[str, str], Answer]) -> str | None:
    """Why the run is offline, or None.

    Offline means *every* lookup failed to reach anything. One failure among many is that one name's problem, not the run's, and saying
    otherwise would throw away a perfectly good report.
    """
    failures = [a for a in answers.values() if isinstance(a, str) and a.startswith("offline")]
    return failures[0] if failures and len(failures) == len(answers) else None


def _judge(dep: Dep, answer: Answer, advisories: tuple[Advisory, ...], held: frozenset[str], hold_reason: str) -> Finding:
    """One dependency's finding. The whole decision table, in the order the questions have to be asked."""
    if dep.version is None:
        # The reader's own reason wins: it knows whether a version is missing because nothing pins one or because what pins it is a commit.
        return Finding(dep, "unpinned", "info", note=dep.note or UNPINNED_NOTES.get(dep.role, UNPINNED_DEFAULT))
    if answer is None:
        return Finding(dep, "unknown", "info", note="not found on the registry")
    if isinstance(answer, str):
        return Finding(dep, "unknown", "info", note=answer)
    if advisories:
        plural = "advisory" if len(advisories) == 1 else "advisories"
        return Finding(dep, "vulnerable", "fail", answer.latest, advisories=advisories, note=f"{len(advisories)} known {plural}")
    if dep.version in answer.withdrawn:
        return Finding(dep, "yanked", "fail", answer.latest, note="this release was withdrawn by its author")
    if is_newer(answer.latest, dep.version, dep.ecosystem, moving=dep.moving):
        kind = update_kind(answer.latest, dep.version)
        if normalize(dep.name) in held:
            return Finding(
                dep,
                "held",
                "info",
                answer.latest,
                kind,
                note=f"held back on purpose: {hold_reason}" if hold_reason else "held back on purpose",
            )
        return Finding(dep, "outdated", "warn", answer.latest, kind)
    return Finding(dep, "current", "ok", answer.latest)


def evaluate(
    deps: Sequence[Dep],
    registries: Registries,
    policy: Policy | None = None,
    today: date | None = None,
    unread: Unread | None = None,
    notes: Sequence[str] = (),
    config_source: str | None = None,
) -> Report:
    """What one run of the check found."""
    today = today or datetime.now(UTC).date()
    unread = unread or Unread()
    policy = policy or Policy()
    ignored = policy.ignored_advisories(today)
    held = policy.held_packages(today)

    answers = _ask_about_every_name(deps, registries)
    offline = _unreachable(answers)

    advisories: Mapping[Coordinate, tuple[Advisory, ...]] = {}
    if not offline:
        wanted = sorted({(d.ecosystem, d.name, d.version) for d in deps if d.version is not None})
        try:
            advisories = registries.advisories(wanted)
        except OfflineError as exc:
            offline = f"offline: {exc}"  # the names resolved but advisories could not be had: the run knows too little to pass
        except RateLimited:
            pass  # no advisory information this run; every finding stays at worst `outdated`, never falsely `current`

    findings = []
    for dep in deps:
        against = advisories.get((dep.ecosystem, normalize(dep.name), dep.version)) if dep.version is not None else None
        relevant = tuple(a for a in (against or ()) if a.id not in ignored and not (set(a.aliases) & ignored))
        findings.append(_judge(dep, answers.get((dep.ecosystem, dep.name)), relevant, held, policy.hold_reason(dep.name, today)))

    return Report(
        findings=tuple(findings),
        policy_problems=policy.problems(today),
        offline=offline,
        today=today.isoformat(),
        unread_manifests=unread.reported,
        accepted_unread=unread.accepted,
        notes=tuple(notes),
        config_source=config_source,
    )

