# stocktake.registries.github
# ======================================================================================================================

"""GitHub releases: the newest release tag of a repository, for the binaries projects download instead of installing from a registry.

These get no advisory check. OSV has no key that identifies "the amd64 tarball from this repository's releases", so claiming to have checked
one would be dishonest; the report says plainly that only the newest tag is known. Mapping a binary back to the module it was built from is
tracked as later work (docs/ROADMAP.md, M6).
"""




class GitHub:
    ecosystem = "GitHub"
    URL = "https://api.github.com/repos/{repo}/releases/latest"

    def __init__(self, cache: Cache) -> None:
        self.cache = cache

    def latest(self, name: str) -> Versions | None:
        """`name` is `owner/repo`. None when there is no repository, or no release at all."""
        data = self.cache.get(self.URL.format(repo=name))
        if not data or not data.get("tag_name"):
            return None
        return Versions(latest=str(data["tag_name"]).removeprefix("v"))

# ======================================================================================================================
# stocktake.registries.npm
# ======================================================================================================================

"""The npm registry: the newest release of a package.

Asks for `/<name>/latest` rather than the whole packument. A popular package's full metadata document runs to megabytes of every version it
has ever published; `latest` is a few hundred bytes and answers the only question being asked.

**npm has no equivalent of a yanked release**, so `withdrawn` is always empty here. It has *deprecated* versions, which is a different and
far looser thing — maintainers deprecate for style, for renames and for "use the other one", not only for danger — and treating deprecation
as withdrawal would fail builds for reasons nobody agreed to. Known vulnerabilities come from OSV, the same as everywhere else.
"""





class Npm:
    ecosystem = "npm"
    URL = "https://registry.npmjs.org/{name}/latest"

    def __init__(self, cache: Cache) -> None:
        self.cache = cache

    def latest(self, name: str) -> Versions | None:
        # A scoped name carries a slash that belongs in the path, so `@` and `/` are kept rather than escaped.
        data = self.cache.get(self.URL.format(name=quote(name, safe="@/")))
        if not data or not data.get("version"):
            return None
        return Versions(latest=str(data["version"]))

# ======================================================================================================================
# stocktake.registries.osv
# ======================================================================================================================

"""OSV (osv.dev): what is publicly known against an exact version.

One batched request asks about every coordinate at once, then each advisory is fetched for its detail. Withdrawn advisories — the ones whose
publishers retracted them — are left out, and what remains is merged so that a GHSA and its PYSEC twin count as one problem rather than two.

The report never says "safe" on the strength of this. OSV's coverage is good for PyPI and npm and absent for plenty else, so the honest claim
is "no known advisories" (NFR-7).
"""





class OSV:
    BATCH_URL = "https://api.osv.dev/v1/querybatch"
    VULN_URL = "https://api.osv.dev/v1/vulns/{id}"

    # Our ecosystem names mapped to OSV's. An ecosystem absent from here is one OSV cannot answer for, and is skipped rather than guessed at.
    # `GitHub` is deliberately absent: OSV has no key that identifies "the amd64 tarball from this repository's releases", and inventing one
    # would mean claiming to have checked something we have not.
    ECOSYSTEMS: Mapping[str, str] = {"PyPI": "PyPI", "npm": "npm"}

    def __init__(self, cache: Cache) -> None:
        self.cache = cache

    def advisories(self, wanted: Sequence[Coordinate]) -> Mapping[Coordinate, tuple[Advisory, ...]]:
        askable = [c for c in wanted if c[0] in self.ECOSYSTEMS]
        if not askable:
            return {}
        body = {
            "queries": [
                {"package": {"name": registry_name(eco, name), "ecosystem": self.ECOSYSTEMS[eco]}, "version": version}
                for eco, name, version in askable
            ]
        }
        result = self.cache.get(self.BATCH_URL, body)

        found: dict[Coordinate, tuple[Advisory, ...]] = {}
        for (eco, name, version), entry in zip(askable, (result or {}).get("results", []), strict=False):
            advisories = []
            for vulnerability in (entry or {}).get("vulns", []):
                detail = self.cache.get(self.VULN_URL.format(id=vulnerability["id"])) or {}
                if detail.get("withdrawn"):
                    continue  # the publisher retracted it; reporting it would be a false positive
                advisories.append(self._advisory(str(vulnerability["id"]), detail, name, eco))
            if advisories:
                found[eco, normalize(name), version] = tuple(merge_advisories(advisories, eco))
        return found

    @staticmethod
    def _advisory(identifier: str, detail: dict[str, Any], name: str, ecosystem: str) -> Advisory:
        """One advisory, keeping only the fixed versions that belong to the package we asked about.

        An advisory often covers several packages at once, so the fixed versions have to be filtered by name or the report ends up naming an
        upgrade target from an entirely different project.
        """
        fixed = sorted(
            {
                event["fixed"]
                for affected in detail.get("affected", [])
                if normalize(str(affected.get("package", {}).get("name", name))) == normalize(name)
                for span in affected.get("ranges", [])
                for event in span.get("events", [])
                if "fixed" in event
            },
            key=lambda version: sort_key(version, ecosystem),
        )
        return Advisory(
            id=identifier,
            severity=str((detail.get("database_specific") or {}).get("severity") or ""),
            summary=(detail.get("summary") or "")[:160],  # a summary, not an essay; the id is there for the full text
            aliases=tuple(str(a) for a in detail.get("aliases") or []),
            fixed=tuple(fixed),
        )

# ======================================================================================================================
# stocktake.registries.pypi
# ======================================================================================================================

"""PyPI: the newest release of a package, and which of its releases have been withdrawn.

A release is counted as withdrawn only when every file in it is yanked. A release with one yanked wheel and a good source distribution is
still installable, and calling that withdrawn would be a false failure.
"""




class PyPI:
    ecosystem = "PyPI"
    URL = "https://pypi.org/pypi/{name}/json"

    def __init__(self, cache: Cache) -> None:
        self.cache = cache

    def latest(self, name: str) -> Versions | None:
        data = self.cache.get(self.URL.format(name=normalize(name)))
        if not data:
            return None
        releases = data.get("releases") or {}
        withdrawn = frozenset(version for version, files in releases.items() if files and all(f.get("yanked") for f in files))
        return Versions(latest=str(data["info"]["version"]), withdrawn=withdrawn)

