# stocktake.readers.python_locks
# ======================================================================================================================

"""Python lock files: `uv.lock`, `pdm.lock`, `poetry.lock` and `Pipfile.lock`.

A lock file is the most honest thing a project has about its dependencies — it names exactly what will be installed, transitively, with no
ranges to interpret. That also makes it the longest list, which is why the report collapses everything current into a count.

The three TOML formats share a shape: an array of `[[package]]` tables with a name and a version. `Pipfile.lock` is JSON and keeps its
sections apart, so where a lock file does record which group an entry serves, that is used; otherwise the role is `locked`.

Entries for the project's own code are skipped. A lock file lists the project itself as a package (`source = {editable = "."}` in uv,
`{virtual = "."}`, a `directory` source in poetry), and asking PyPI about your own unreleased package produces a confusing `unknown`.
"""




TOML_LOCKS = frozenset({"uv.lock", "pdm.lock", "poetry.lock"})

# A source of this kind means "code that lives in this repository", not something a registry knows about.
LOCAL_SOURCES = frozenset({"editable", "virtual", "directory", "path", "url", "git"})


def is_toml_lock(path: Path) -> bool:
    return path.name in TOML_LOCKS


def is_pipfile_lock(path: Path) -> bool:
    return path.name == "Pipfile.lock"


def _is_local(package: dict[str, Any]) -> bool:
    source = package.get("source")
    if isinstance(source, dict):
        return any(key in source for key in LOCAL_SOURCES)
    return False


def _toml_packages(data: dict[str, Any]) -> Iterator[tuple[str, str]]:
    packages = data.get("package")
    if not isinstance(packages, list):
        return
    for package in packages:
        if not isinstance(package, dict) or _is_local(package):
            continue
        name, version = package.get("name"), package.get("version")
        if isinstance(name, str) and isinstance(version, str) and name and version:
            yield name, version


@reader("python", is_toml_lock)
def read_toml_lock(path: Path, text: str, context: Context) -> Iterable[Dep]:
    """Packages resolved by a uv, pdm or poetry lock file."""
    try:
        data = tomllib.loads(text)
    except tomllib.TOMLDecodeError:
        return  # a damaged lock file is the project's problem to notice, not this tool's to crash on
    for name, version in _toml_packages(data):
        yield Dep("PyPI", name, version, context.source(path), f"=={version}", "locked")


@reader("python", is_pipfile_lock)
def read_pipfile_lock(path: Path, text: str, context: Context) -> Iterable[Dep]:
    """Packages resolved by a Pipfile.lock, keeping the section each one came from."""
    try:
        data = json.loads(text)
    except ValueError:
        return
    if not isinstance(data, dict):
        return
    for section, role in (("default", "locked"), ("develop", "dev")):
        entries = data.get(section)
        if not isinstance(entries, dict):
            continue
        for name, detail in entries.items():
            if not isinstance(detail, dict):
                continue
            # Pipenv writes the version as a specifier, "==2.31.0". Anything else (a git ref, a local path) has no version to check.
            spec = detail.get("version")
            version = spec.removeprefix("==") if isinstance(spec, str) and spec.startswith("==") else None
            if version is None:
                continue
            yield Dep("PyPI", str(name), version, context.source(path), f"=={version}", role)

# ======================================================================================================================
# stocktake.readers.python_project
# ======================================================================================================================

"""`pyproject.toml` and `Pipfile`: what a Python project *declares*, checked at the version actually present.

A declared range is not a version. `pytest>=8` tells you nothing about what is running, so where the package is installed in this environment
that installed version is what gets checked, and the range is kept alongside it as the specifier. Where it is not installed, there is nothing
to check and it is reported as unpinned instead of being quietly dropped.

(Lock files are the other way round — the pin wins there, because a lock file names what *will* be installed. See `python_locks.py`.)
"""





def is_pyproject(path: Path) -> bool:
    return path.name == "pyproject.toml"


def is_pipfile(path: Path) -> bool:
    return path.name == "Pipfile"


def _declared(data: dict[str, object]) -> Iterator[tuple[str, str]]:
    """Every requirement string in the file, with the role it plays."""
    project = data.get("project")
    if isinstance(project, dict):
        for item in project.get("dependencies") or []:
            if isinstance(item, str):
                yield item, "runtime"
        optional = project.get("optional-dependencies")
        if isinstance(optional, dict):
            for group in optional.values():
                for item in group or []:
                    if isinstance(item, str):
                        yield item, "dev"
    # PEP 735 dependency groups, which uv writes. An entry may be `{include-group = "..."}` rather than a requirement.
    groups = data.get("dependency-groups")
    if isinstance(groups, dict):
        for group in groups.values():
            for item in group or []:
                if isinstance(item, str):
                    yield item, "dev"


@reader("python", is_pyproject)
def read_pyproject(path: Path, text: str, context: Context) -> Iterable[Dep]:
    """Dependencies declared in pyproject.toml, at the version installed in this environment."""
    try:
        data = tomllib.loads(text)
    except tomllib.TOMLDecodeError:
        return  # a broken pyproject.toml is that project's problem to report, not this tool's to crash on
    for entry, role in _declared(data):
        parsed = parse_requirement(entry)
        if parsed is None:
            continue
        name, pinned, spec = parsed
        yield Dep("PyPI", name, context.installed(name) or pinned, context.source(path), spec, role)


def _pipfile_spec(value: object) -> str | None:
    """The specifier a Pipfile entry holds: `"*"`, `">=2.0"`, or `{version = "==4.2", extras = [...]}`. None when there is no version at all."""
    if isinstance(value, str):
        return value
    if isinstance(value, dict):
        version = value.get("version")
        return version if isinstance(version, str) else None
    return None


@reader("python", is_pipfile)
def read_pipfile(path: Path, text: str, context: Context) -> Iterable[Dep]:
    """Dependencies declared in a Pipfile, at the version installed in this environment.

    Read so that a project using pipenv is not told its Pipfile is an unreadable manifest while its lock file is being read perfectly well.
    """
    try:
        data = tomllib.loads(text)
    except tomllib.TOMLDecodeError:
        return
    for section, role in (("packages", "runtime"), ("dev-packages", "dev")):
        entries = data.get(section)
        if not isinstance(entries, dict):
            continue
        for name, value in entries.items():
            spec = _pipfile_spec(value)
            if spec is None:
                continue
            tidy = "" if spec.strip() in ("*", "") else spec.strip()
            pinned = tidy.removeprefix("==") if tidy.startswith("==") else None
            yield Dep("PyPI", str(name), context.installed(str(name)) or pinned, context.source(path), tidy, role)

# ======================================================================================================================
# stocktake.readers.python_requirements
# ======================================================================================================================

"""`requirements*.txt` and `constraints*.txt`: a resolved set, usually fully pinned.

The version rule here is the opposite of `pyproject.toml`'s, deliberately. A `pyproject.toml` entry declares a *range*, which says nothing
about what is actually running, so the installed version wins. A requirements file names what *will* be installed, so the pin wins, and the
installed version is consulted only where there is no pin.

The file format is mostly "one requirement per line", with four things that catch a naive reader out: backslash continuations, `--hash=`
digests trailing a requirement, pip options that are not requirements at all (`-r`, `-e`, `--index-url`), and direct references
(`name @ https://...`) where the URL is the version and there is nothing to ask a registry about.
"""




FILE_PATTERNS = ("requirements*.txt", "constraints*.txt")

# A requirements file whose name says what it is for: the role is informational, and a filename is the only hint these files give.
# Matched whole, so the plurals have to be listed too.
DEV_WORDS = frozenset({"dev", "develop", "development", "test", "tests", "lint", "lints", "doc", "docs", "ci", "typing"})


def is_requirements_file(path: Path) -> bool:
    return any(fnmatch(path.name, pattern) for pattern in FILE_PATTERNS)


def requirement_in(line: str) -> str:
    """The requirement a line holds, or an empty string when it holds something else."""
    text = re.sub(r"(^|\s)#.*$", "", line).strip()
    if not text or text.startswith("-"):
        return ""  # a pip option. Where it points at another file, that file is walked on its own account.
    if " @ " in text or text.startswith(("http://", "https://", "git+", "file:")):
        return ""  # a direct reference: the URL fixes it, and no registry can be asked about it
    return text.split("--hash")[0].strip()


def role_of(path: Path) -> str:
    """`dev` when the filename says so, else `runtime`. A guess, but the only information the format offers.

    Matched as whole words, not substrings: `requirements-social.txt` contains "ci" and is not a CI requirements file.
    """
    words = re.split(r"[^a-z0-9]+", path.stem.lower())
    return "dev" if any(word in DEV_WORDS for word in words) else "runtime"


@reader("python", is_requirements_file)
def read_requirements(path: Path, text: str, context: Context) -> Iterable[Dep]:
    """Dependencies listed in a requirements or constraints file."""
    role = role_of(path)
    for number, line in logical_lines(text):
        entry = requirement_in(line)
        if not entry:
            continue
        parsed = parse_requirement(entry)
        if parsed is None:
            continue
        name, pinned, spec = parsed
        yield Dep("PyPI", name, pinned or context.installed(name), context.source(path, number), spec, role)

# ======================================================================================================================
# stocktake.readers.workflows
# ======================================================================================================================

"""GitHub Actions: the versions a workflow pins.

`uses: owner/repo@ref` is a dependency on somebody else's code, running inside the repository with access to its secrets, and it is invisible
to everything that reads package manifests. It is also the one kind of dependency people routinely pin to a commit SHA — which is the right
thing to do and makes the version unreadable. So where the line carries the conventional version comment beside the SHA, that is used:

    uses: actions/checkout@08c6903cd8c0fde910a37f88322edcfb5dd907a8  # v5.0.0

A ref that names no version at all is reported with the reason, never silently dropped. An action tracking `@main` and an action pinned to a
commit are both uncheckable, but for opposite reasons, and the report says which.
"""




USES_LINE = re.compile(r"^\s*(?:-\s+)?uses:\s*(?P<value>.+)$")
VERSION_REF = re.compile(r"^v?\d+(?:\.\d+)*$")
COMMIT_REF = re.compile(r"^[0-9a-f]{40}$")
VERSION_IN_COMMENT = re.compile(r"\bv?(\d+(?:\.\d+)*)\b")

# Referring to the repository's own code, or to a container, rather than to a published action.
LOCAL_OR_CONTAINER = ("./", ".\\", "../", "docker://")

COMMIT_NOTE = "pinned to a commit, which cannot be compared with a release; name the version in a comment (`# v5.0.0`) and it will be"
MOVING_NOTE = "tracks a branch or a named ref, so which code runs depends on when the workflow runs"


def is_workflow(path: Path) -> bool:
    """A GitHub Actions workflow, or an action definition — both of which pin other actions."""
    if path.suffix not in (".yml", ".yaml"):
        return False
    if path.stem == "action":
        return True
    return path.parent.name == "workflows" and path.parent.parent.name == ".github"


@dataclass(frozen=True, slots=True)
class Used:
    """One `uses:` reference, and what could be made of its ref."""

    repo: str
    ref: str
    line: int
    version: str | None = None
    note: str = ""
    moving: bool = False


def workflow_uses(text: str) -> list[Used]:
    """Every action the file uses, with the ref read as far as it can be."""
    found = []
    for number, raw in enumerate(text.splitlines(), 1):
        match = USES_LINE.match(raw)
        if not match:
            continue
        value, _, comment = match.group("value").partition("#")
        value = value.strip().strip("'\"")
        if not value or value.startswith(LOCAL_OR_CONTAINER):
            continue
        target, separator, ref = value.partition("@")
        segments = target.split("/")
        if not separator or not ref.strip() or len(segments) < 2:
            continue  # no ref at all, or not an owner/repo reference
        found.append(_read_ref("/".join(segments[:2]), ref.strip(), comment, number))
    return found


def _read_ref(repo: str, ref: str, comment: str, line: int) -> Used:
    if VERSION_REF.match(ref):
        version = ref.removeprefix("v")
        # `@v7` and `@v7.1` are tags GitHub advances as it releases; `@v7.1.0` is one by convention nobody moves.
        return Used(repo, ref, line, version, moving=version.count(".") < 2)
    if COMMIT_REF.match(ref):
        hint = VERSION_IN_COMMENT.search(comment)
        return Used(repo, ref, line, hint.group(1)) if hint else Used(repo, ref, line, note=COMMIT_NOTE)
    return Used(repo, ref, line, note=MOVING_NOTE)


@reader("workflows", is_workflow)
def read_workflow_actions(path: Path, text: str, context: Context) -> Iterable[Dep]:
    """Actions a GitHub Actions workflow pins."""
    for used in workflow_uses(text):
        yield Dep(
            "GitHub",
            used.repo,
            used.version,
            context.source(path, used.line),
            f"@{used.ref}",
            "ci",
            used.note,
            used.moving,
        )

