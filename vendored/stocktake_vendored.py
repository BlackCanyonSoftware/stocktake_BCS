# stocktake.scan
# ======================================================================================================================

"""Walking a project and handing each file to whichever readers want it.

Two jobs, and the second matters as much as the first. One is to collect what the project declares. The other is to notice a manifest of a
kind no reader understands, because the dangerous failure for a tool like this is not a wrong answer, it is a clean-looking report that
quietly missed half the project.
"""




# Files that declare dependencies in some form. A kind no registered reader is interested in gets reported as unread rather than ignored,
# which is what turns "StockTake does not support this yet" from a silent gap into something the project is told about.
MANIFEST_KINDS: tuple[str, ...] = (
    "requirements*.txt",
    "constraints*.txt",
    "Pipfile",
    "Pipfile.lock",
    "poetry.lock",
    "uv.lock",
    "pdm.lock",
    "environment.yml",
    "environment.yaml",
    "package.json",
    "package-lock.json",
    "yarn.lock",
    "pnpm-lock.yaml",
    "bun.lockb",
    "go.mod",
    "Cargo.toml",
    "Gemfile",
    "Gemfile.lock",
    "composer.json",
    "*.csproj",
    "pom.xml",
    "build.gradle",
    "build.gradle.kts",
    ".pre-commit-config.yaml",
)


VENV_NAMES = (".venv", "venv")

NO_ENVIRONMENT_NOTE = (
    "No Python environment was found for this project, so dependencies declared as a range could not be resolved to a version. "
    "Point at one with --environment PATH, or run StockTake from inside the project's own environment."
)


@dataclass(frozen=True, slots=True)
class Environment:
    """Which Python environment "what is installed" was read from, and what was in it."""

    versions: dict[str, str] | None  # None means none could be found; {} means one was found and is empty
    label: str  # where it came from, in words, for the report

    @property
    def found(self) -> bool:
        return self.versions is not None

    def version(self, name: str) -> str | None:
        return (self.versions or {}).get(normalize(name))


def _site_packages(base: Path) -> list[Path]:
    """Where an environment keeps its installed packages, on either platform."""
    return [*base.glob("Lib/site-packages"), *base.glob("lib/python*/site-packages")]


def _read_site_packages(sites: Sequence[Path]) -> dict[str, str] | None:
    """`{normalised name: version}` read from `*.dist-info` directory names, which carry both without opening a single file.

    None when there was no such directory to read at all, which is different from an environment that exists and is empty.
    """
    if not sites:
        return None
    found: dict[str, str] = {}
    for site in sites:
        try:
            entries = sorted(site.glob("*.dist-info"))
        except OSError:
            continue
        for dist_info in entries:
            name, _, version = dist_info.name.removesuffix(".dist-info").rpartition("-")
            if name and version:
                found.setdefault(normalize(name), version)
    return found


def _this_interpreter() -> dict[str, str]:
    found: dict[str, str] = {}
    for dist in metadata.distributions():
        name = dist.metadata["Name"] if dist.metadata else None
        if name:
            found.setdefault(normalize(str(name)), dist.version)
    return found


def _same_place(left: Path, right: Path) -> bool:
    try:
        return left.resolve() == right.resolve()
    except OSError:
        return False


def _inside(root: Path, candidate: str) -> bool:
    try:
        return Path(candidate).resolve().is_relative_to(root.resolve())
    except (OSError, ValueError):
        return False


def find_environment(root: Path, environment: Path | None = None) -> Environment:
    """The environment whose installed versions should be used for the project at `root`.

    In order: one the caller named, the project's own `.venv` or `venv`, the environment active in this shell when it is this very project
    being checked, and the interpreter running StockTake when that happens to be the project's environment.

    Where none of those holds, nothing is claimed. Reporting a version out of somebody else's environment — StockTake's own, when it is
    installed as a standalone tool, or a different project's when `--root` points elsewhere — would be a wrong answer on a security check,
    which is worse than admitting we do not know (NFR-7).
    """
    if environment is not None:
        return Environment(_read_site_packages(_site_packages(environment)), str(environment))

    for name in VENV_NAMES:
        versions = _read_site_packages(_site_packages(root / name))
        if versions is not None:
            return Environment(versions, name)

    active = os.environ.get("VIRTUAL_ENV")
    if active and _same_place(root, Path.cwd()):
        versions = _read_site_packages(_site_packages(Path(active)))
        if versions is not None:
            return Environment(versions, "the active virtual environment")

    if _inside(root, os.environ.get("VIRTUAL_ENV") or sys.prefix):
        return Environment(_this_interpreter(), "the interpreter running StockTake")

    return Environment(None, "none found")


def installed_version(name: str) -> str | None:
    """The version of a package present in *this* interpreter's environment, or None when it is not installed."""
    try:
        return metadata.version(name)
    except metadata.PackageNotFoundError:
        return None


def installed_for(root: Path, environment: Path | None = None) -> InstalledFn:
    """How to answer "what version is installed" for the project being checked."""
    return find_environment(root, environment).version


def iter_files(root: Path, excludes: Sequence[str]) -> Iterator[Path]:
    """Every file under root, in a stable order, without descending into the folders the project excluded.

    The pruning is not an optimisation to be skipped: a single virtual environment holds tens of thousands of files, most of them manifests
    belonging to somebody else's package.
    """
    for dirpath, dirnames, filenames in os.walk(root):
        here = Path(dirpath)
        dirnames[:] = sorted(d for d in dirnames if not excluded((here / d).relative_to(root).as_posix(), excludes))
        for name in sorted(filenames):
            path = here / name
            if not excluded(path.relative_to(root).as_posix(), excludes):
                yield path


def _declares_npm_dependencies(text: str) -> bool:
    """Whether a package.json actually declares dependencies, as opposed to being a bare manifest holding only scripts or metadata."""
    try:
        data = json.loads(text)
    except ValueError:
        return False
    return isinstance(data, dict) and any(
        data.get(key) for key in ("dependencies", "devDependencies", "optionalDependencies", "peerDependencies")
    )


@dataclass(frozen=True, slots=True)
class Scan:
    """What walking a project turned up: what it declares, and what could not be read.

    The second half is not an afterthought. A scan that returned only the dependencies had nowhere to put "I was meant to read this file and
    failed", so it dropped it, and a project whose `package.json` was truncated got a clean report (docs/adr/0009).
    """

    deps: list[Dep] = field(default_factory=list)
    unreadable: list[Unreadable] = field(default_factory=list)


def scan(root: Path, config: Config | None = None, installed: InstalledFn | None = None, groups: Sequence[str] | None = None) -> Scan:
    """Every dependency the project declares, in the order the files were walked, and every manifest that defeated its reader.

    `installed` answers what is present in the project's environment; the default works it out with `installed_for`.

    Which readers run comes from the project's `ecosystems` setting, so a project that only wants its Python pins checked never loads the npm
    reader and never asks the npm registry anything. `groups` overrides that, for tests and for a caller that knows better.
    """
    config = config or Config()
    context = Context(root=root, installed=installed or installed_for(root))
    chosen = groups if groups is not None else config.ecosystems
    active = [r for r in READERS if chosen is None or r.group in chosen]

    found = Scan()
    for path in iter_files(root, config.excludes):
        wanted = [r for r in active if r.interested(path)]
        if not wanted:
            continue
        relative = path.relative_to(root).as_posix()
        try:
            text = read_manifest(path)
        except UnreadableManifest as exc:
            found.unreadable.append(Unreadable(relative, exc.reason))
            continue
        for one in wanted:
            try:
                # Readers are generators, so the reading happens here and a failure surfaces here. Whatever a reader managed to yield before
                # giving up is kept: those dependencies are real, and the file is reported as unreadable alongside them.
                found.deps.extend(one.read(path, text, context))
            except UnreadableManifest as exc:
                found.unreadable.append(Unreadable(relative, exc.reason))
    return found


def unread_manifests(root: Path, config: Config | None = None) -> Unread:
    """Dependency manifests of a kind no registered reader understands, relative to the project root.

    Adding a reader shrinks this on its own, which is the point: it is derived from what the readers claim to be interested in, never from a
    hard-coded list of what is supported.

    A project may accept one in its config, which stops it being reported — but it is still carried in `Unread.accepted` and in the JSON
    report, because an unchecked surface that has become invisible is exactly what this tool exists to prevent.
    """
    config = config or Config()
    reported: list[str] = []
    accepted: list[str] = []
    for path in iter_files(root, config.excludes):
        if any(r.interested(path) for r in READERS):
            continue
        if not any(fnmatch(path.name, kind) for kind in MANIFEST_KINDS):
            continue
        if path.name == "package.json":
            try:
                if not _declares_npm_dependencies(read_manifest(path)):
                    continue
            except UnreadableManifest:
                pass  # it could not be read, so whether it declares anything is unknown — which is a reason to name it, not to drop it
        relative = path.relative_to(root).as_posix()
        (accepted if excluded(relative, config.accept_unread) else reported).append(relative)
    return Unread(tuple(sorted(reported)), tuple(sorted(accepted)))

# ======================================================================================================================
# stocktake.check
# ======================================================================================================================

"""One run of the check, and the three questions everybody asking gets the same answer to.

The command line, a project's test suite and a CI step all want the same thing: a report, and then whether it should stop the build, whether
something is worth a warning, and whether the check could be made at all.

Those rules are [ADR 0004](adr/0004-only-unsafe-findings-fail-the-build.md), and they live here exactly once. If the pytest plugin worked
them out for itself, the two would drift, and a project's test suite would start disagreeing with what `stocktake` says on the same project.
"""




# How many outdated dependencies the warning names before it stops listing and just counts. A warning nobody can read is not a warning.
NAMED_IN_WARNING = 12


def _environment_path(root: Path, named: str | None) -> Path | None:
    if named is None:
        return None
    chosen = Path(named).expanduser()
    return chosen if chosen.is_absolute() else root / chosen  # a path in a config file means a path in that project


def notes_about(deps: Sequence[Dep], environment_found: bool) -> list[str]:
    """What a reader needs to know about this run in order to judge the findings in it.

    Each note is tied to the ecosystem it is about, which is not a detail: a run against a project with no Python in it was telling its owner
    to point StockTake at a Python environment, which is advice that cannot help and makes the rest of the report look less careful than it is.
    """
    notes = []
    if not environment_found and any(d.ecosystem == "PyPI" and d.version is None and d.role != "image" for d in deps):
        # A Dockerfile's unpinned install is about what the image will build, not about which environment we looked in.
        notes.append(NO_ENVIRONMENT_NOTE)
    if any(d.ecosystem == "npm" and d.version is None for d in deps):
        notes.append(RUN_INSTALL_NOTE)
    return notes


def run_check(
    root: Path,
    *,
    config: Config | None = None,
    config_path: Path | None = None,
    environment: str | None = None,
    registries: Registries | None = None,
    installed: InstalledFn | None = None,
    today: date | None = None,
    refresh: bool = False,
) -> Report:
    """Read the project, ask the registries about what it found, and judge the answers.

    Raises `ConfigError` when the project's configuration cannot be used — including a named environment that does not exist, because someone
    who went to the trouble of naming one does not want a silent fallback to a different one.
    """
    settings = config if config is not None else load_config(root, config_path)

    environment_found = True
    lookup = installed
    if lookup is None:
        chosen = _environment_path(root, environment or settings.environment)
        found = find_environment(root, chosen)
        if chosen is not None and not found.found:
            raise ConfigError(f"no Python environment found at {chosen}")
        lookup, environment_found = found.version, found.found

    scanned = scan(root, settings, lookup)
    # Nothing to say when the caller supplied the answers itself: advice about where to find them is not ours to give.
    notes = [] if installed is not None else notes_about(scanned.deps, environment_found)

    asking = registries if registries is not None else Registries(Cache(ttl=settings.cache_ttl_seconds, refresh=refresh))
    report = evaluate(
        scanned.deps,
        asking,
        settings.policy,
        today,
        unread_manifests(root, settings),
        notes,
        settings.source,
        scanned.unreadable,
    )
    asking.flush()
    return report


def skip_reason(report: Report) -> str | None:
    """Why this check could not be made at all, or None.

    A test suite skips on this and stays green. Being unable to ask is not a finding, and turning a network blip into a red build is how a
    check like this gets switched off.
    """
    return f"cannot reach the registries ({report.offline})" if report.offline else None


def incomplete_text(report: Report) -> str | None:
    """What to say when part of the project could not be read at all, or None when all of it was.

    Kept apart from `failure_text`, which is about what was found. This is about what was never looked at, and it is the more serious of the
    two: a wrong answer gets argued with, while a missing one reads as a clean bill of health. It raises rather than skips because a test
    suite has no exit code to carry the distinction, and a warning in a pytest summary is how this became invisible in the first place
    (docs/adr/0009).
    """
    if report.nothing_was_checked:
        count = len(report.unread_manifests)
        files = "file" if count == 1 else "files"
        named = ", ".join(report.unread_manifests)
        return (
            f"StockTake checked nothing in this project. The only {count} dependency {files} it found "
            f"({named}) are of a kind it has no reader for yet, so this run says nothing about the project either way.\n"
            "\n"
            "If that is expected, list them in `accept_unread` in the project's config and this becomes a pass again."
        )

    if not report.unreadable:
        return None
    count = len(report.unreadable)
    files = "file" if count == 1 else "files"
    lines = [f"StockTake could not read {count} dependency {files}, so this project was not fully checked:"]
    lines += [f"  {item.path} {item.reason}" for item in report.unreadable]
    lines.append("")
    lines.append("Fix the file, or exclude it in the project's config if it is not meant to be read.")
    return "\n".join(lines)


def problems(report: Report) -> str | None:
    """Everything wrong with this run and with this project, as one message, or None when there is nothing to say.

    The incomplete part comes first when both apply: it says how much of what follows to trust.
    """
    trouble = [text for text in (incomplete_text(report), failure_text(report)) if text is not None]
    return "\n".join(trouble) if trouble else None


def assert_safe(root: Path | str = ".", **kwargs: Any) -> Report:
    """Run the check and raise `AssertionError` carrying the whole report when something is wrong. Returns the report when nothing is.

    For a project driving StockTake from a plain script or a non-pytest test runner — which the single-file copy exists for. The obvious
    thing to write by hand is `assert failure_text(report) is None`, and a trial run found what that costs: a bare `AssertionError` with a
    traceback and not one word about the package, the advisory or the fix. The person whose build just went red learns nothing.

    Raises rather than returning a flag so it cannot be ignored, and raises `AssertionError` specifically so a test runner reports it as a
    failed assertion rather than an error in the tooling. The rules are `problems`, which is the same pair of rules the pytest plugin and the
    command line use; nothing here decides anything of its own.
    """
    report = run_check(Path(root), **kwargs)
    message = problems(report)
    if message is not None:
        raise AssertionError(message)
    return report


def update_warning(report: Report) -> str | None:
    """The "there are newer releases" message, or None when everything is current. A warning, never a failure (ADR 0004)."""
    outdated = [f for f in report.findings if f.status == "outdated"]
    if not outdated:
        return None
    listed = ", ".join(f"{f.dep.name} {f.dep.version}->{f.latest}" for f in outdated[:NAMED_IN_WARNING])
    more = " ..." if len(outdated) > NAMED_IN_WARNING else ""
    return f"{len(outdated)} dependencies have a newer release: {listed}{more}  (run `stocktake` for the full report)"


def failure_text(report: Report) -> str | None:
    """What to say when this should stop the build, or None when nothing should.

    The report itself is the message. Narrowed to what must be fixed, because a failure that also lists thirteen merely-old packages is a
    failure people learn to skim.

    The first line says what happened in words. pytest prints the first line of an assertion message after the dash in its one-line summary,
    and this used to begin with a blank line, so every failing run showed `FAILED stocktake_dependency_check - ` and nothing after it.
    """
    if not report.failed:
        return None
    counts = report.counts
    parts = [f"{counts[status]} {word}" for status, word in (("vulnerable", "vulnerable"), ("yanked", "withdrawn")) if counts[status]]
    if report.policy_problems:
        entries = "entry" if len(report.policy_problems) == 1 else "entries"
        parts.append(f"{len(report.policy_problems)} policy {entries} overdue")
    return f"StockTake found {', '.join(parts)}.\n\n" + render_text(report, "vulnerable")

