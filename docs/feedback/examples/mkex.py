"""Builds the small example projects with known answers. Run: python mkex.py OUTDIR"""
import json
import sys
from pathlib import Path

out = Path(sys.argv[1])


def w(rel, text):
    p = out / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8", newline="\n")


